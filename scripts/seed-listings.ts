// Writes supabase/migrations/..._seed_listings.sql from the catalogue in src/data/listings.ts.
// Run: npx tsx scripts/seed-listings.ts
import { writeFileSync } from 'node:fs'
import { LISTINGS } from '../src/data/listings'

const q = (s: string) => `'${s.replace(/'/g, "''")}'`
const rows = LISTINGS.map(
  (l) => `  (${q(l.id)}, ${q(l.title)}, ${q(l.city)}, ${l.price}, ${l.cleaningFee}, ${l.guests}, ${l.instantBook})`,
)
const sql = `-- Generated by scripts/seed-listings.ts. Catalogue homes and their prices.
insert into public.listings (id, title, city, price, cleaning_fee, max_guests, instant_book) values
${rows.join(',\n')}
on conflict (id) do update set
  title = excluded.title, city = excluded.city, price = excluded.price,
  cleaning_fee = excluded.cleaning_fee, max_guests = excluded.max_guests, instant_book = excluded.instant_book;
`
writeFileSync('supabase/migrations/20261121000100_seed_listings.sql', sql)
console.log(`${rows.length} homes`)
